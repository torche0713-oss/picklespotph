// ============================================================
// Generate booking-links.js from enriched data
// ============================================================
// Usage: node scripts/generate-booking-links.js
// ============================================================

const fs = require('fs');
const path = require('path');

const ENRICHED_FILE = path.resolve(__dirname, '..', 'js', 'booking-links-enriched.json');
const OUTPUT_FILE = path.resolve(__dirname, '..', 'js', 'booking-links.js');
const DASHBOARD_FILE = path.resolve(__dirname, '..', 'js', 'dashboard.js');

function loadEnriched() {
  let raw = fs.readFileSync(ENRICHED_FILE, 'utf8');
  if (raw.charCodeAt(0) === 0xFEFF) raw = raw.slice(1);
  return JSON.parse(raw);
}

// Extract website URLs and Facebook pages from IMPORT_COURTS notes/contact
function extractFromImportCourts() {
  const results = [];
  const raw = fs.readFileSync(DASHBOARD_FILE, 'utf8');
  const start = raw.indexOf('const IMPORT_COURTS = [');
  const end = raw.indexOf('];', start);
  if (start === -1 || end === -1) return results;
  
  const arrStr = raw.substring(start + 'const IMPORT_COURTS = '.length, end + 1);
  try {
    const courts = eval('(' + arrStr + ')');
    const urlRegex = /(?:https?:\/\/)?(?:www\.)?([a-zA-Z0-9][-a-zA-Z0-9]*\.[a-z]{2,}(?:\.[a-z]{2})?(?:\/[^\s,]*)?)/gi;
    
    for (const c of courts) {
      const slug = c.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      
      // Check notes for website URLs
      if (c.notes) {
        const urls = c.notes.match(urlRegex);
        if (urls) {
          for (const url of urls) {
            if (!url.match(/facebook|fb\.me|@/i) && !url.match(/^\d+$/) && !url.match(/^picklers\.website/i)) {
              const fullUrl = url.startsWith('http') ? url : 'https://' + url;
              const u = fullUrl.toLowerCase();
              if (u.includes('onda.fit')) {
                results.push({ slug, platform: 'Onda Fit', url: fullUrl, label: 'Book via Onda Fit' });
              } else if (u.includes('sports360')) {
                results.push({ slug, platform: 'Sport360', url: fullUrl, label: 'Book via Sport360' });
              } else if (u.includes('playserve')) {
                results.push({ slug, platform: 'PlayServe', url: fullUrl, label: 'Book via PlayServe' });
              } else if (u.includes('picklehub')) {
                results.push({ slug, platform: 'PickleHub', url: fullUrl, label: 'Listed on PickleHub' });
              } else {
                results.push({ slug, platform: 'Website', url: fullUrl, label: 'Visit Website' });
              }
            }
          }
        }
      }
      
      // Check contact for website URLs
      if (c.contact) {
        const urls = c.contact.match(urlRegex);
        if (urls) {
          for (const url of urls) {
            if (!url.match(/facebook|fb\.me|@/i) && !url.match(/^\d+$/) && !url.match(/^picklers\.website/i)) {
              const fullUrl = url.startsWith('http') ? url : 'https://' + url;
              results.push({ slug, platform: 'Website', url: fullUrl, label: 'Visit Website' });
            }
          }
        }
      }
    }
  } catch (e) {}
  
  return results;
}

function generate() {
  console.log('=== Generating booking-links.js ===\n');
  
  const enriched = loadEnriched();
  const importUrls = extractFromImportCourts();
  
  console.log(`Loaded ${enriched.enrichedCount} enriched entries`);
  console.log(`Found ${importUrls.length} URLs from IMPORT_COURTS\n`);
  
  // Build the booking links
  const lines = [];
  
  lines.push('// ============================================================');
  lines.push('// BOOKING LINKS — Court booking platform URL lookup table');
  lines.push('// ============================================================');
  lines.push('// Auto-generated by scripts/generate-booking-links.js');
  lines.push(`// Generated: ${new Date().toISOString().split('T')[0]}`);
  lines.push('// ============================================================');
  lines.push('');
  lines.push('const BOOKING_BY_ID = {');
  
  const bookings = enriched.bookings;
  const slugs = Object.keys(bookings).sort();
  
  for (const slug of slugs) {
    const entry = bookings[slug];
    if (!entry.booking) continue;
    
    const b = entry.booking;
    const url = b.url.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    
    lines.push(`  "${slug}": {`);
    
    if (b.platform === 'Courtogo') {
      lines.push(`    courtogo: '${url}',`);
    } else if (b.platform === 'Onda Fit') {
      lines.push(`    onda: '${url}',`);
    } else if (b.platform === 'Sport360') {
      lines.push(`    sports360: '${url}',`);
    } else if (b.platform === 'PlayServe') {
      lines.push(`    playserve: '${url}',`);
    } else if (b.platform === 'PickleHub') {
      lines.push(`    picklehub: '${url}',`);
    } else if (b.platform === 'Website') {
      lines.push(`    website: '${url}',`);
    }
    
    lines.push(`    platform: '${b.platform}',`);
    lines.push(`    label: '${b.label}'`);
    lines.push('  },');
  }
  
  // Add IMPORT_COURTS extracted URLs (avoiding duplicates)
  for (const ie of importUrls) {
    const existing = bookings[ie.slug];
    if (existing && existing.booking) continue;
    
    lines.push(`  "${ie.slug}": {`);
    const url = ie.url.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    
    if (ie.platform === 'Onda Fit') {
      lines.push(`    onda: '${url}',`);
    } else if (ie.platform === 'Sport360') {
      lines.push(`    sports360: '${url}',`);
    } else if (ie.platform === 'PlayServe') {
      lines.push(`    playserve: '${url}',`);
    } else if (ie.platform === 'PickleHub') {
      lines.push(`    picklehub: '${url}',`);
    } else {
      lines.push(`    website: '${url}',`);
    }
    
    lines.push(`    platform: '${ie.platform}',`);
    lines.push(`    label: '${ie.label}'`);
    lines.push('  },');
  }
  
  lines.push('};');
  lines.push('');
  
  // Add the helper functions (reuse from existing file)
  lines.push('// ============================================================');
  lines.push('// Lookup function');
  lines.push('// ============================================================');
  lines.push('function getBookingInfo(courtId, courtName) {');
  lines.push('  const key = courtId || (courtName ? courtName.toLowerCase().replace(/[^a-z0-9]+/g, \'-\').replace(/^-|-$/g, \'\') : \'\');');
  lines.push('  return BOOKING_BY_ID[key] || null;');
  lines.push('}');
  lines.push('');
  lines.push('// ============================================================');
  lines.push('// Helper: generate "Book Now" button HTML');
  lines.push('// ============================================================');
  lines.push('function getBookingButtonHtml(courtId, courtName) {');
  lines.push('  const info = getBookingInfo(courtId, courtName);');
  lines.push('  if (!info) return \'\';');
  lines.push('  ');
  lines.push('  const url = info.courtogo || info.onda || info.sports360 || info.playserve || info.picklehub || info.website || info.facebook;');
  lines.push('  if (!url) return \'\';');
  lines.push('  ');
  lines.push('  const colorMap = {');
  lines.push('    \'Onda Fit\': \'#6366f1\',');
  lines.push('    \'Courtogo\': \'#0891b2\',');
  lines.push('    \'Sport360\': \'#059669\',');
  lines.push('    \'PlayServe\': \'#7c3aed\',');
  lines.push('    \'PickleHub\': \'#ea580c\',');
  lines.push('    \'Website\': \'#2563eb\',');
  lines.push('    \'Facebook\': \'#1877f2\'');
  lines.push('  };');
  lines.push('  const color = colorMap[info.platform] || \'#2563eb\';');
  lines.push('  ');
  lines.push('  return \'<a href="\'+url+\'" target="_blank" rel="noopener" class="btn-submit" style="display:block;text-align:center;background:\'+color+\';margin-top:8px"><i class="fas fa-external-link-alt"></i> \'+info.label+\'</a>\';');
  lines.push('}');
  lines.push('');
  lines.push('// Make available globally');
  lines.push('if (typeof window !== \'undefined\') {');
  lines.push('  window.BOOKING_BY_ID = BOOKING_BY_ID;');
  lines.push('  window.getBookingInfo = getBookingInfo;');
  lines.push('  window.getBookingButtonHtml = getBookingButtonHtml;');
  lines.push('}');
  
  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'));
  console.log(`Written ${lines.length} lines to ${OUTPUT_FILE}`);
}

generate();
